def dt(day_offset: int, hour: int, minute: int = 0) -> str:
    """Return ISO datetime string for base date + offset."""
    return (BASE_DATE + timedelta(days=day_offset, hours=hour, minutes=minute)).isoformat()


def date_str(days_ago: int) -> str:
    """Return ISO date string for today - days_ago."""
    return (BASE_DATE - timedelta(days=days_ago)).strftime("%Y-%m-%d")


